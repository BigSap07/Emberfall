# ---------------------------------------------------------------------------------- baseline drift

Section 'Baseline drift' {
    Add '### Harness baselines (Tools/DevHarness)'
    Add ''
    if (-not $BuildCheck) {
        Add '**Not run:** status.ps1 was invoked on its own, and the harness output these come from exists only inside a build-check run.'
    } elseif (-not $BuildCheck.HarnessRan) {
        Add ('**Not run:** the harness did not run in the build-check that produced this file' +
             $(if ($BuildCheck -and $BuildCheck.HarnessNote) { ' (' + $BuildCheck.HarnessNote + ')' } else { '' }) + '.')
    } else {
        Add 'Source: the harness output of this build-check run.'
        Add ''
        $lines = @($BuildCheck.HarnessLines)
        foreach ($b in @(@{ Kind = 'stage'; File = 'stage-fingerprint-baseline.txt' },
                         @{ Kind = 'sweep'; File = 'hero-sweep-baseline.txt' },
                         @{ Kind = 'talent'; File = 'talent-sweep-baseline.txt' })) {
            $match = $lines | Where-Object { $_ -match ('(\ball (\d+) ' + $b.Kind + ' fingerprints match\b|(\d+) of (\d+) ' + $b.Kind + ' fingerprints MOVED)') } | Select-Object -First 1
            if (-not $match) { Add ('- `' + $b.File + '`: **not compared** in this run (no line for it in the output).'); continue }
            $moved = [regex]::Match($match, '(\d+) of (\d+) ' + $b.Kind + ' fingerprints MOVED: (.*)$')
            if ($moved.Success) {
                Add ('- `' + $b.File + '`: **' + $moved.Groups[1].Value + ' of ' + $moved.Groups[2].Value + ' entries moved**:')
                Add ''
                Add ('  ' + ((($moved.Groups[3].Value -split ',\s*') | ForEach-Object { '`' + $_ + '`' }) -join ' '))
                Add ''
            } else {
                $all = [regex]::Match($match, 'all (\d+) ')
                Add ('- `' + $b.File + '`: all ' + $all.Groups[1].Value + ' entries match, none moved.')
            }
            $extra = $lines | Where-Object { $_ -match ('\[FAIL\].*' + $b.Kind + ' fingerprint.*(not in the baseline|lost)') }
            foreach ($e in $extra) { Add ('  - ' + ($e -replace '^\s*\[FAIL\]\s*', '')) }
        }
    }

    Add ''
    Add '### Tools/doc-lint-baseline.txt'
    Add ''
    $baselinePath = Join-Path $root 'Tools\doc-lint-baseline.txt'
    $baseline = @(Get-Content $baselinePath | ForEach-Object { $_ -replace "^\uFEFF", '' } | Where-Object { $_.Trim() })
    $lint = @(& powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $PSScriptRoot 'doc-lint.ps1') 2>&1 | ForEach-Object { "$_" })
    $found = @{}
    $newOnes = New-Object System.Collections.Generic.List[string]
    $section = ''
    foreach ($l in $lint) {
        if ($l -match 'NEW violations') { $section = 'new'; continue }
        if ($l -match 'baselined \(known debt') { $section = 'old'; continue }
        $e = [regex]::Match($l, '^\s{4}(\S+):\d+\s+(\S+)\s+(\S+)\s*$')
        if (-not $e.Success) { continue }
        $entry = $e.Groups[1].Value + '|' + $e.Groups[3].Value
        $found[$entry] = $true
        if ($section -eq 'new') { $newOnes.Add($entry + '  (' + $e.Groups[2].Value + ')') }
    }
    $gone = @($baseline | Where-Object { -not $found.ContainsKey($_) })
    Add ('Source: a `Tools/doc-lint.ps1` run made by this script, against the ' + $baseline.Count + ' entries in the baseline. ' +
         'Still present: ' + ($baseline.Count - $gone.Count) + '. Gone from the docs (fixed, or the line was rewritten): ' +
         $gone.Count + '. New, not in the baseline: ' + $newOnes.Count + '.')
    if ($gone.Count -gt 0) { Add ''; Add 'Gone:'; foreach ($g in $gone) { Add ('- `' + $g + '`') } }
    if ($newOnes.Count -gt 0) { Add ''; Add 'New:'; foreach ($n in $newOnes) { Add ('- `' + $n + '`') } }
}

