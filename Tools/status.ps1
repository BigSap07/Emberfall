# Writes STATUS.md at the repository root: what is true of this checkout right now, every figure
# with the file, command or run it came from. STATUS.md is gitignored. It is regenerated, never
# edited, and never committed: a status that lived in git would be a document's prior claim the
# moment the next commit landed, which is exactly what it exists to replace.
#
#   powershell -ExecutionPolicy Bypass -File Tools/status.ps1
#
# build-check.ps1 calls it as its last step and passes in what that run found (-BuildCheck), so
# the build-check and baseline-drift sections describe a run that actually happened. Run on its
# own, those sections say "not run" rather than guessing. The same goes for the two Supabase rule
# tests: a test counts only if its run record (Tools/SupabaseRuns, gitignored, written by the test
# itself) was made at the commit being described. An older record is named, and its numbers are
# not carried.
#
# IT CANNOT FAIL THE BUILD. Each section is computed inside its own try/catch and a section that
# breaks says so in the file. build-check.ps1 additionally wraps the whole call, so neither its
# exit code nor its failure count can be changed by anything here.
#
# Nothing here touches the network: origin/main is read as of the last fetch, and the time of that
# fetch is printed beside it.

param(
    # From build-check.ps1. Keys: ExitCode (int), Failures (string[]), HarnessRan (bool),
    # HarnessNote (string), HarnessLines (string[]).
    [hashtable]$BuildCheck
)

$ErrorActionPreference = 'Continue'
$root = Split-Path -Parent $PSScriptRoot
$outPath = Join-Path $root 'STATUS.md'
$md = New-Object System.Collections.Generic.List[string]
$unmergedForConsole = New-Object System.Collections.Generic.List[string]

function Add([string]$line) { $md.Add($line) }

# Git with stderr kept out of the error stream; the verdict is the exit code. NOT named Git:
# PowerShell resolves a function before an executable, so a function called Git that runs git calls
# itself until the stack runs out.
function Invoke-StatusGit {
    $previous = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $out = & git -C $root @args 2>$null
        $script:GitExit = $LASTEXITCODE
        return $out
    } finally { $ErrorActionPreference = $previous }
}

function Section([string]$title, [scriptblock]$body) {
    Add ''
    Add "## $title"
    Add ''
    try { & $body }
    catch { Add ("**This section could not be computed:** " + $_.Exception.Message) }
}

# The content files carry // and /* */ comments, which ContentDatabase's reader accepts and
# ConvertFrom-Json does not. Strings are matched first and kept, so a // inside one survives.
function Read-ContentJson([string]$path) {
    $text = [IO.File]::ReadAllText($path)
    $clean = [regex]::Replace($text, '("(?:\\.|[^"\\])*")|//[^\r\n]*|/\*[\s\S]*?\*/', '$1')
    $clean = [regex]::Replace($clean, '("(?:\\.|[^"\\])*")|,(\s*[\]}])', '$1$2')
    return ($clean | ConvertFrom-Json)
}

$head = "$(Invoke-StatusGit rev-parse HEAD)".Trim()

# ------------------------------------------------------------------------------------------ header

Add '# Emberfall status'
Add ''
Add 'Generated by `Tools/status.ps1`. Gitignored and regenerated on every build-check; do not edit or commit it.'
Add 'Every figure names its source. A figure that could not be produced says so instead of carrying an old one.'

Section 'Where this is' {
    $branch = "$(Invoke-StatusGit rev-parse --abbrev-ref HEAD)".Trim()
    $originMain = "$(Invoke-StatusGit rev-parse --verify --quiet origin/main)".Trim()
    $commonDir = "$(Invoke-StatusGit rev-parse --git-common-dir)".Trim()
    if ($commonDir -and -not [IO.Path]::IsPathRooted($commonDir)) { $commonDir = Join-Path $root $commonDir }
    $fetchHead = if ($commonDir) { Join-Path $commonDir 'FETCH_HEAD' } else { '' }
    $fetched = if ($fetchHead -and (Test-Path $fetchHead)) {
        (Get-Item $fetchHead).LastWriteTimeUtc.ToString('yyyy-MM-dd HH:mm:ss') + ' UTC'
    } else { 'unknown (no FETCH_HEAD)' }
    Add '| | | source |'
    Add '|---|---|---|'
    Add ('| generated | ' + (Get-Date).ToUniversalTime().ToString('yyyy-MM-dd HH:mm:ss') + ' UTC | system clock |')
    Add ('| branch | `' + $branch + '` | `git rev-parse --abbrev-ref HEAD` |')
    Add ('| HEAD | `' + $head + '` | `git rev-parse HEAD` |')
    $mainText = if ($originMain) { '`' + $originMain + '`' } else { 'not found' }
    Add ('| origin/main | ' + $mainText + ' | `git rev-parse origin/main`, as of the last fetch |')
    Add ('| last fetch | ' + $fetched + ' | modification time of FETCH_HEAD |')
}

# -------------------------------------------------------------------------------- unmerged branches

Section 'Branches not merged into origin/main' {
    $originMain = "$(Invoke-StatusGit rev-parse --verify --quiet origin/main)".Trim()
    if (-not $originMain) { Add 'origin/main is not known to this clone, so nothing can be compared to it.'; return }
    $rows = @(Invoke-StatusGit for-each-ref --no-merged=origin/main --sort=-committerdate `
                  '--format=%(refname)|%(refname:short)|%(committerdate:short)' refs/heads refs/remotes/origin)
    $rows = @($rows | Where-Object { $_ -and $_ -notmatch '^refs/remotes/origin/HEAD\|' })
    Add ('Source: `git for-each-ref --no-merged=origin/main refs/heads refs/remotes/origin`, and per branch ' +
         '`git rev-list --left-right --count origin/main...<branch>`. Ahead is commits the branch has that ' +
         'origin/main does not; behind is the reverse. Newest first. ' + $rows.Count + ' branch(es).')
    Add ''
    if ($rows.Count -eq 0) { Add 'None.'; return }
    Add '| branch | ahead | behind | last commit |'
    Add '|---|---:|---:|---|'
    foreach ($row in $rows) {
        $parts = $row.Split('|')
        $counts = "$(Invoke-StatusGit rev-list --left-right --count "origin/main...$($parts[0])")".Trim() -split '\s+'
        $behind = if ($counts.Count -ge 2) { $counts[0] } else { '?' }
        $ahead = if ($counts.Count -ge 2) { $counts[1] } else { '?' }
        $label = if ($parts[0] -like 'refs/heads/*') { $parts[1] } else { $parts[1] + ' (remote)' }
        Add ('| `' + $label + '` | ' + $ahead + ' | ' + $behind + ' | ' + $parts[2] + ' |')
        $unmergedForConsole.Add(('  {0,-48} +{1,-5} -{2,-6} {3}' -f $label, $ahead, $behind, $parts[2]))
    }
}

# ------------------------------------------------------------------------------------- build-check

Section 'build-check' {
    if (-not $BuildCheck) {
        Add ('**Not run.** status.ps1 was invoked on its own; the figures here come only from a ' +
             '`Tools/build-check.ps1` run, which calls this script as its last step and passes in what it found.')
        return
    }
    $failures = @($BuildCheck.Failures | Where-Object { $_ })
    Add ('Source: the `Tools/build-check.ps1` run that generated this file. Exit code ' + $BuildCheck.ExitCode +
         ', **' + $failures.Count + ' failure(s)**.')
    if ($BuildCheck.HarnessNote) { Add ''; Add ('Harness: ' + $BuildCheck.HarnessNote) }
    if ($failures.Count -gt 0) {
        Add ''
        foreach ($f in $failures) { Add ('- ' + $f) }
    }
}

# --------------------------------------------------------------------------------- hero validator

Section 'Hero validator' {
    $validator = Join-Path $root 'Tools\HeroValidator\validate_heroes.py'
    $heroesJson = Join-Path $root 'Assets\Resources\Content\heroes.json'
    $python = Get-Command python -ErrorAction SilentlyContinue
    if (-not $python) { Add '**Not run:** no `python` on PATH.'; return }
    $out = @(& $python.Source -I $validator $heroesJson 2>&1 | ForEach-Object { "$_" })
    $code = $LASTEXITCODE
    $summary = $out | Where-Object { $_ -match '^Summary:' } | Select-Object -Last 1
    $checked = @($out | Where-Object { $_ -match '^\S+(  OK)?$' -and $_ -notmatch '^(Summary|DUPLICATE)' }).Count
    Add ('Source: `python Tools/HeroValidator/validate_heroes.py Assets/Resources/Content/heroes.json`, exit ' + $code + '.')
    Add ''
    if ($summary) { Add ('' + $checked + ' hero(es) checked. ' + $summary) }
    else { Add ('**No summary line.** Last output: ' + (($out | Select-Object -Last 3) -join ' / ')) }
}

# ------------------------------------------------------------------------------- supabase rule tests

Section 'Supabase rule tests' {
    Add ('Source: the run record each test writes when it finishes, in `Tools/SupabaseRuns/` (gitignored). ' +
         'A test counts as run only if its record was made at HEAD; status.ps1 never calls the live project.')
    Add ''
    foreach ($t in @(@{ Name = 'Tools/supabase-rules-test.py'; File = 'rules.json' },
                     @{ Name = 'Tools/supabase-guild-rules-test.py'; File = 'guild.json' })) {
        $path = Join-Path $root ('Tools\SupabaseRuns\' + $t.File)
        if (-not (Test-Path $path)) { Add ('- `' + $t.Name + '`: **not run** (no run record).'); continue }
        $rec = Get-Content $path -Raw | ConvertFrom-Json
        if ($rec.commit -and $rec.commit -eq $head) {
            Add ('- `' + $t.Name + '`: ran at HEAD, ' + $rec.utc + ': ' + $rec.passes + ' ok, ' + $rec.failures + ' FAILED.')
        } else {
            $at = if ($rec.commit) { $rec.commit.Substring(0, [Math]::Min(10, $rec.commit.Length)) } else { 'an unknown commit' }
            Add ('- `' + $t.Name + '`: **not run** at HEAD. (The last record is from ' + $rec.utc + ' at ' + $at +
                 '; its counts describe that commit and are not carried here.)')
        }
    }
}

# ---------------------------------------------------------------------------------- content counts

Section 'Content' {
    $dir = Join-Path $root 'Assets\Resources\Content'
    Add ('Source: `Assets/Resources/Content/*.json`, comments stripped and parsed. Each top-level ' +
         'list is counted by its entries and each top-level object by its keys; scalars are skipped.')
    Add ''
    Add '| file | counts |'
    Add '|---|---|'
    foreach ($file in (Get-ChildItem $dir -Filter *.json | Sort-Object Name)) {
        try {
            $data = Read-ContentJson $file.FullName
            $parts = @()
            if ($data -is [array]) { $parts += ('' + $data.Count + ' entries') }
            else {
                foreach ($p in $data.PSObject.Properties) {
                    if ($p.Name -like '_*') { continue }
                    if ($p.Value -is [array]) { $parts += ($p.Name + ' ' + $p.Value.Count) }
                    elseif ($p.Value -is [System.Management.Automation.PSCustomObject]) {
                        $parts += ($p.Name + ' ' + @($p.Value.PSObject.Properties).Count + ' keys')
                    }
                }
            }
            $text = if ($parts.Count -gt 0) { $parts -join ', ' } else { 'scalars only' }
            Add ('| ' + $file.Name + ' | ' + $text + ' |')
        } catch {
            Add ('| ' + $file.Name + ' | could not be parsed: ' + $_.Exception.Message + ' |')
        }
    }
}

# ------------------------------------------------------------------------------------ art coverage

Section 'Art coverage (battle sprites)' {
    $content = Join-Path $root 'Assets\Resources\Content'
    $units = Join-Path $root 'Assets\Resources\Sprites\Units'
    Add ('Source: `visual.sprite` and `visual.spriteStatus` in heroes.json and enemies.json, against the files in ' +
         '`Assets/Resources/Sprites/Units`. The rule is the harness''s CheckSpriteDelivery: drawn means ' +
         '`<sprite>_idle.png` with its `.json`, or `<sprite>.png`, exists; pending means spriteStatus "pending" ' +
         '(the shared mannequin); broken means art is declared and absent; procedural means no sprite is named.')
    Add ''
    Add '| | total | drawn | pending | broken | procedural |'
    Add '|---|---:|---:|---:|---:|---:|'
    foreach ($kind in @(@{ File = 'heroes.json'; Key = 'heroes' }, @{ File = 'enemies.json'; Key = 'enemies' })) {
        $data = Read-ContentJson (Join-Path $content $kind.File)
        $list = @($data.($kind.Key))
        $drawn = 0; $pending = 0; $broken = 0; $procedural = 0
        foreach ($u in $list) {
            $sprite = "$($u.visual.sprite)"
            $resolves = $false
            if ($sprite) {
                $resolves = ((Test-Path (Join-Path $units ($sprite + '_idle.png'))) -and
                             (Test-Path (Join-Path $units ($sprite + '_idle.json')))) -or
                            (Test-Path (Join-Path $units ($sprite + '.png')))
            }
            if ("$($u.visual.spriteStatus)" -eq 'pending') { if ($resolves) { $broken++ } else { $pending++ } }
            elseif (-not $sprite) { $procedural++ }
            elseif ($resolves) { $drawn++ }
            else { $broken++ }
        }
        Add ('| ' + $kind.Key + ' | ' + $list.Count + ' | ' + $drawn + ' | ' + $pending + ' | ' + $broken + ' | ' + $procedural + ' |')
    }
    Add ''
    Add 'A pending unit whose file has landed is counted as broken here (the harness calls it STALE): it renders the mannequin while its art sits unused.'
}

