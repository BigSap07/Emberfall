"""Writes Tools/DevHarness/sprite-extents.txt: where each finished battle sprite's visible pixels sit.

For every sheet in Assets/Resources/Sprites/Units that has an idle clip, the union over all idle frames of
the pixels whose alpha is above 40, as fractions of one frame: x0 and x1 from the left edge, ybot and ytop
from the bottom edge. The mannequin (placeholder_dummy.png) is one still image and is measured the same way.

The harness (StageChecks.cs) turns these into world-space silhouettes with the same arithmetic UnitRig.BuildSprite
uses, and proves that no two bodies, plates or bars overlap in the v2 layout. Re-run this when a sheet changes:

    python Tools/sprite_extents.py

Needs Pillow and numpy. Reads the art, never writes it.
"""
import json
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UNITS = os.path.join(ROOT, "Assets", "Resources", "Sprites", "Units")
OUT = os.path.join(ROOT, "Tools", "DevHarness", "sprite-extents.txt")
OUT_JSON = os.path.join(ROOT, "Assets", "Resources", "Content", "sprite-extents.json")


def idle_bbox(sprite):
    with open(os.path.join(UNITS, sprite + "_idle.json"), encoding="utf-8") as f:
        side = json.load(f)
    anim = side["defaultAnimation"]
    fw, fh = side["frameWidth"], side["frameHeight"]
    cols = side["sheet"]["cols"]
    alpha = np.array(Image.open(os.path.join(UNITS, sprite + "_idle.png")).convert("RGBA"))[:, :, 3]
    x0, x1, y0, y1 = fw, 0, fh, 0
    for i in range(anim["start"], anim["end"] + 1):
        c, r = i % cols, i // cols
        frame = alpha[r * fh:(r + 1) * fh, c * fw:(c + 1) * fw] > 40
        xs = np.nonzero(frame.any(axis=0))[0]
        ys = np.nonzero(frame.any(axis=1))[0]
        if len(xs) == 0:
            continue
        x0, x1 = min(x0, xs.min()), max(x1, xs.max() + 1)
        y0, y1 = min(y0, ys.min()), max(y1, ys.max() + 1)
    return fw, fh, x0, x1, y0, y1


def still_bbox(name):
    alpha = np.array(Image.open(os.path.join(UNITS, name + ".png")).convert("RGBA"))[:, :, 3] > 40
    h, w = alpha.shape
    xs = np.nonzero(alpha.any(axis=0))[0]
    ys = np.nonzero(alpha.any(axis=1))[0]
    return w, h, xs.min(), xs.max() + 1, ys.min(), ys.max() + 1


def main():
    names = sorted(f[:-len("_idle.png")] for f in os.listdir(UNITS) if f.endswith("_idle.png"))
    lines = ["# sprite id | frame width | frame height | x0 | x1 | ybot | ytop (fractions of one frame, y from the bottom)",
             "# generated by Tools/sprite_extents.py, read by Tools/DevHarness/StageChecks.cs"]
    rows = [(n, idle_bbox(n)) for n in names]
    rows.append(("placeholder_dummy", still_bbox("placeholder_dummy")))
    for name, (fw, fh, x0, x1, y0, y1) in rows:
        lines.append("%s|%d|%d|%.4f|%.4f|%.4f|%.4f" % (name, fw, fh, x0 / fw, x1 / fw, 1 - y1 / fh, 1 - y0 / fh))
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    # The game reads the same two numbers per sprite (ybot, ytop) from Resources, so the unit's head is where
    # the art's head is (SpriteExtents). Same rounding as the text file; the harness holds the two equal.
    jlines = ["{", '  // Written by Tools/sprite_extents.py: [ybot, ytop] of each sprite, fractions of one frame, y from the bottom.',
              '  // Presentation only, never read by ContentDatabase, so not part of ContentVersion.', '  "sprites": {']
    for i, (name, (fw, fh, x0, x1, y0, y1)) in enumerate(rows):
        jlines.append('    "%s": [%.4f, %.4f]%s' % (name, 1 - y1 / fh, 1 - y0 / fh, "," if i < len(rows) - 1 else ""))
    jlines += ["  }", "}"]
    with open(OUT_JSON, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(jlines) + "\n")
    print("wrote %d sprites to %s" % (len(rows), OUT))


if __name__ == "__main__":
    sys.exit(main())
